// Generates the Material 3 colour scheme (src/styles/scheme.css) from the seeds in
// src/content/themeSeeds.json, run before every build.
//
// - app.source is the sea and sky of the beach photo of 2020 (web/static/photos/2020-1-*), picked
//   with the QuantizerCelebi + Score of this library. app.sand, the sand of the same photo, sets
//   the tertiary palette so the accents come from the beach instead of a computed hue rotation.
// - each edition's seed comes from its old poster the same way, and tints its card in the history.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
    argbFromHex,
    DynamicScheme,
    Hct,
    hexFromArgb,
    MaterialDynamicColors,
    SchemeVibrant,
    TonalPalette,
} from "@material/material-color-utilities";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const seeds = JSON.parse(fs.readFileSync(path.join(root, "src/content/themeSeeds.json"), "utf8"));
const output = path.join(root, "src/styles/scheme.css");

// Every M3 colour role, as `--md-sys-color-<kebab-case role>`
const ROLES = [
    "primary",
    "onPrimary",
    "primaryContainer",
    "onPrimaryContainer",
    "inversePrimary",
    "secondary",
    "onSecondary",
    "secondaryContainer",
    "onSecondaryContainer",
    "tertiary",
    "onTertiary",
    "tertiaryContainer",
    "onTertiaryContainer",
    "error",
    "onError",
    "errorContainer",
    "onErrorContainer",
    "background",
    "onBackground",
    "surface",
    "onSurface",
    "surfaceVariant",
    "onSurfaceVariant",
    "surfaceDim",
    "surfaceBright",
    "surfaceContainerLowest",
    "surfaceContainerLow",
    "surfaceContainer",
    "surfaceContainerHigh",
    "surfaceContainerHighest",
    "inverseSurface",
    "inverseOnSurface",
    "outline",
    "outlineVariant",
    "shadow",
    "scrim",
    "surfaceTint",
];
// The roles an edition card redefines: its accents and its surfaces
const EDITION_ROLES = [
    "primary",
    "onPrimary",
    "primaryContainer",
    "onPrimaryContainer",
    "secondaryContainer",
    "onSecondaryContainer",
    "surfaceContainerLow",
    "surfaceContainer",
    "surfaceContainerHigh",
];

const kebab = (role) => role.replace(/[A-Z]/g, (letter) => "-" + letter.toLowerCase());

const appScheme = (isDark) => {
    const source = Hct.fromInt(argbFromHex(seeds.app.source));
    const vibrant = new SchemeVibrant(source, isDark, 0);
    const sand = Hct.fromInt(argbFromHex(seeds.app.sand));

    return new DynamicScheme({
        sourceColorArgb: source.toInt(),
        variant: vibrant.variant,
        contrastLevel: 0,
        isDark,
        primaryPalette: vibrant.primaryPalette,
        secondaryPalette: vibrant.secondaryPalette,
        tertiaryPalette: TonalPalette.fromHueAndChroma(sand.hue, 40),
        neutralPalette: vibrant.neutralPalette,
        neutralVariantPalette: vibrant.neutralVariantPalette,
    });
};

const editionScheme = (seed, isDark) =>
    new SchemeVibrant(Hct.fromInt(argbFromHex(seed)), isDark, 0);

const declarations = (scheme, roles, indent) =>
    roles
        .map(
            (role) =>
                `${indent}--md-sys-color-${kebab(role)}: ${hexFromArgb(
                    MaterialDynamicColors[role].getArgb(scheme),
                )};`,
        )
        .join("\n");

const block = (selector, body) => `${selector} {\n${body}\n}\n`;

// Light by default, dark when the system asks for it unless the user chose light, or when the
// user chose dark (data-theme on <html>, set by the theme toggle)
const themed = (selector, schemeFor, roles, colorScheme) => {
    const light = declarations(schemeFor(false), roles, "    ");
    const dark = declarations(schemeFor(true), roles, "    ");
    const darkInMedia = declarations(schemeFor(true), roles, "        ");
    const scheme = (value, indent) => (colorScheme ? `${indent}color-scheme: ${value};\n` : "");

    return [
        block(selector, scheme("light", "    ") + light),
        `@media (prefers-color-scheme: dark) {\n` +
            `    :root:not([data-theme="light"]) ${selector === ":root" ? "" : selector + " "}{\n` +
            scheme("dark", "        ") +
            darkInMedia +
            `\n    }\n}\n`,
        block(
            `:root[data-theme="dark"]${selector === ":root" ? "" : " " + selector}`,
            scheme("dark", "    ") + dark,
        ),
    ].join("\n");
};

const css = [
    "/* Generated by scripts/generate-theme.mjs from src/content/themeSeeds.json: do not edit */\n",
    themed(":root", appScheme, ROLES, true),
    ...Object.entries(seeds.editions).map(([year, seed]) =>
        themed(`.edition-${year}`, (isDark) => editionScheme(seed, isDark), EDITION_ROLES, false),
    ),
].join("\n");

fs.writeFileSync(output, css);
console.log("Colour scheme written to " + path.relative(root, output));
